/*
Package certifiedchain builds a SealRegistry deployment and a chain of certified EVM blocks for tests: a
deployment generated by registrygenesis, blocks whose registry storage is finalized for their rounds in real
state tries, and unicity certificates really signed over the full shard configuration with a fixed key, so a
child process builds certificates a parent's trust base accepts.

It imports no store or node package, so their own package-internal tests can use it.
*/
