	custodyNetwork             = 4
	custodyRoots               = 8
	custodyLimits              = 11
	custodyLastAckedAssignment = 14
	custodyRecordCursor        = 15
	custodyPositions           = 22
	custodyGenerationLots      = 26
	custodyLots                = 27
	custodyRetirements         = 28
	custodyExposureChain       = 29
	custodyMaxLiabilityAnchor  = 30
	custodyLiveExposures       = 31
	custodyAssignments         = 32
	custodySessions            = 35
