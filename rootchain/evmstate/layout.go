// Package evmstate verifies Ethereum account and storage proofs of the P85 custody and registry contracts against the EVM state root the
// root already certified, and reads from them the facts a Retirement or RejectResult control needs
// (briefs/p85-pr1c-control-records.md sections 3 and 4).
package evmstate

import (
	"math/big"

	ethcrypto "github.com/ethereum/go-ethereum/crypto"
)

// The declared storage layout. Custody's slots are the solc layout of unicity-pos-contracts src/p85/StakeCustody.sol (variables in
// declaration order, one slot per word, struct members packed from the low-order byte); the registry's are fixed slots named
// keccak256("unicity.seal-registry/" + name). Every slot used here was checked against the slots the EVM itself reads for the matching
// public getter: testdata/state-slots.json and testdata/registry-state-slots.json are generated by the contracts' own tests.
